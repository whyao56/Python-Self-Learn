'''理论'''
'''
让程序做决策——`if / elif / else`
到目前为止，程序都是“一条路走到底”。但现实生活中有很多**分支选择**，比如：
- 如果今天下雨，就带伞；否则不带。
- 考试分数 >= 60 分，就及格；否则不及格。

Python 中用 `if` 语句来实现这种逻辑。

### 🌰 先看例子（判断年龄是否成年）
```python
# 让用户输入年龄，然后判断是否成年
age = int(input("请输入你的年龄："))   # 先拿到字符串，立刻转整数

if age >= 18:
    print("你已经是成年人了！")        # 条件满足时执行
else:
    print("你还是未成年人。")          # 条件不满足时执行
```

### 📖 理论解释（用红绿灯类比）
- **if** 就像路口的一个**检查站**：它会问“条件满足吗？”（比如 `age >= 18`）
- 如果**对**（True），就走 `if` 下面的代码块（绿灯通过）。
- 如果**不对**（False），就走 `else` 下面的代码块（红灯绕行）。
- `elif` 是“否则如果”，可以增加多个检查站（比如多个分数段），我们后面会见到。

### 🔍 关键语法细节
1. **条件后面必须有冒号 `:`**
2. **缩进**：`if` 和 `else` 下面的代码**必须缩进**（按 Tab 键或 4 个空格）。PyCharm 会自动帮你缩进。
3. 比较运算符：`>=`（大于等于）、`<=`（小于等于）、`==`（等于，注意是两个等号）、`!=`（不等于）。
'''


'''问题'''
'''
写一个程序：询问用户“今天气温是多少度？”（输入后转为整数）。
- 如果温度 `>= 30`，打印“太热了，开空调吧！”
- 否则打印“天气不错，出去走走吧！”
'''

what_today_temp = float(input("今天气温是多少度："))
if what_today_temp >= 30:
    print("太热了，开空调吧!")
else:
    print("天气不错，出去走走吧！")
