'''理论'''
'''
第六课：字典（dict）——键值对的集合
列表只能通过索引取元素，但有时候我们需要**用名字来找东西**。比如：
- 查某人电话号码：通过姓名找号码
- 存储用户信息：`{"姓名":"小明", "年龄":18, "城市":"北京"}`

这就是**字典**，用 `{}` 包裹，每个元素都是一对 `键: 值`。

### 🌰 例子：通讯录
```python
# 创建字典
contact = {
    "姓名": "小明",
    "电话": "13800138000",
    "邮箱": "xiaoming@example.com"
}

# 查：通过键获取值
print(contact["姓名"])         # 小明
print(contact.get("电话"))     # get 方法，找不到也不会报错

# 改 / 增
contact["电话"] = "13900000000"   # 修改已有键的值
contact["城市"] = "北京"          # 新增一个键值对

# 删
del contact["邮箱"]

# 遍历字典的键和值
for key, value in contact.items():
    print(f"{key}: {value}")
```

### 📖 理论解释
- 字典像一本**电话簿**：你想找“小明”的号码，就翻到“小明”那一页，而不是数页码。
- 键（key）通常是字符串或数字，值（value）可以是任意类型。
- 字典是**无序**的（Python 3.7+ 维护插入顺序，但逻辑上是映射关系）。
- `.items()` 方法返回一个可遍历的 (键, 值) 对。
'''


'''问题'''
'''
1. 创建一个字典 `student`，包含以下键值对：
   - "姓名"："小丽"
   - "年龄"：20
   - "成绩"：88
2. 打印学生的姓名和年龄。
3. 将“成绩”修改为 92。
4. 添加一个新的键“城市”，值为“上海”。
5. 最后用 `for` 循环遍历打印所有信息。
'''


'''回答'''
student = {
    "姓名": "小丽",
    "年龄": "20",
    "成绩": "88"
}

print(student["姓名"])
print(student["年龄"])
student["成绩"] = 92
student["城市"] = "上海"

for key, value in student.items():
    print(f"{key}: {value}")


'''优化建议'''
'''
年龄和成绩应该存为 数字（整数），而非字符串："年龄": 20，"成绩": 88
因为后续可能需要计算（比如“成绩加5分”），如果存为字符串就无法数学运算，还得 int() 转换，麻烦且容易出错。
你后面修改成绩为 92 就是整数，这步很正确，说明你已经意识到类型问题，只是初始值习惯性加了引号。
'''