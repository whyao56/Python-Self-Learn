'''理论'''
'''
从 while 到 for：两种循环的对比

我们已经学了 **while 循环**，它的特点是“**当条件满足就一直做**”。
但还有一种场景：**我有一个集合，想把它里面的每个元素都拿出来一个个处理**。比如：
- 打印一个名单列表里的所有人名
- 计算购物车里所有商品的总价
- 对一堆学生成绩分别判断及格与否

这种“**遍历**”行为，用 **for 循环** 会更简洁、更安全。我们先看一个对比：

```python
# while 遍历一个列表（需要手动管理索引）
fruits = ["苹果", "香蕉", "橘子"]
i = 0                     # 索引从0开始
while i < len(fruits):    # len() 获取列表长度
    print(fruits[i])
    i += 1

# for 遍历同样列表（自动取出每一个）
fruits = ["苹果", "香蕉", "橘子"]
for fruit in fruits:
    print(fruit)
```

看到区别了吗？`for` 循环**不需要索引、不需要手动递增**，直接把列表里的每个元素赋值给变量 `fruit`，循环完一遍自动停止。

### 📖 理论解释：for 循环就是“逐个点名”
想象你有一盒彩色铅笔（列表），你要一支支拿出来用。
- **while** 的方式：你一边拿一边自己数“第1支、第2支……”直到盒子空。
- **for** 的方式：你说“把这盒笔一支支递给我”，它会自动递给你每一支，直到递完。

Python 中，**for 循环**专门用来遍历**可迭代对象**（如列表、字符串、字典等），写法为：
```python
for 变量 in 可迭代对象:
    做点什么
```

---

## 🚀 引入列表（我们马上就会展开讲）
上面 `fruits = ["苹果", "香蕉", "橘子"]` 就是一个**列表**（list），用于存放多个数据。你可以把它看成一排带编号的抽屉，编号从0开始：
- `fruits[0]` → "苹果"
- `fruits[1]` → "香蕉"
- `fruits[2]` → "橘子"

我们下节课会系统学习列表的创建、增删改查，现在只需要知道列表可以配合 for 循环遍历。
'''


'''题目'''
'''
### 🎯 练习9（模仿题）
下面是一个**班级成绩列表**，请用 for 循环**遍历并逐个打印**每个成绩，并在打印时判断：如果成绩 >= 60，打印“及格”，否则打印“不及格”。
```python
scores = [85, 42, 93, 67, 58]   # 这是给定的列表，直接使用
```
期望输出格式（举例）：
```
85 分：及格
42 分：不及格
...
'''


'''回答'''
scores = [85, 42, 93, 67, 58]

i = 0
while i < len(scores):
    print(scores[i])
    if scores[i] < 60:
        print(f"{scores[i]}，不及格")
    elif scores[i] > 60:
        print(f"{scores[i]}，及格")
    else:
        print("成绩出错")
    i += 1


'''优化'''
scores = [85, 42, 93, 67, 58]
for score in scores:          # 直接取出每个分数
    if score >= 60:
        print(f"{score}分：及格")
    else:
        print(f"{score}分：不及格")
