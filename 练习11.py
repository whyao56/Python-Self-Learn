'''理论'''
'''
列表（List）——数据的有序集合

你已经见过列表了：`scores = [85,42,93,67,58]`。
**列表** 就像一个**带编号的储物柜**，每个位置可以放任何 Python 对象，编号从 0 开始。

### 🌰 先看例子：列表的基本操作
```python
# 创建列表
fruits = ["苹果", "香蕉", "橘子"]

# 索引（取出单个元素）
print(fruits[0])   # 苹果
print(fruits[1])   # 香蕉
print(fruits[2])   # 橘子
# print(fruits[3]) # 会报错 IndexError，因为只有3个元素

# 切片（取出子列表）
print(fruits[0:2])  # ['苹果', '香蕉']（左闭右开，不含索引2）

# 增删改
fruits.append("葡萄")        # 在末尾添加
print(fruits)                # ['苹果', '香蕉', '橘子', '葡萄']

fruits[1] = "草莓"           # 修改索引1的元素
print(fruits)                # ['苹果', '草莓', '橘子', '葡萄']

del fruits[2]                # 删除索引2的元素
print(fruits)                # ['苹果', '草莓', '葡萄']
```

### 📖 理论解释
- **列表（list）**：用 `[]` 包裹，元素间用逗号隔开。
- **索引**：从 0 开始，负数索引表示从末尾倒数（`fruits[-1]` 是最后一个元素）。
- **切片**：`[start:end]` 截取子列表，含 start，不含 end。
- **`.append(元素)`**：往列表最后添加一个元素。
- **`del`**：根据索引删除元素。
- 列表中的元素**类型可以混合**，比如 `["小明", 18, True]`，但我们通常保持类型一致。
'''



'''题目'''
'''
1. 创建一个空列表，命名为 `tasks`。
2. 依次添加三个待办事项（字符串）："写作业", "跑步", "读书"。
3. 打印整个列表。
4. 修改第二个待办事项为 "看电影"。
5. 删除最后一个事项。
6. 打印最终列表和它的长度（用 `len()`）。
'''

'''回答'''
tasks = []

tasks.append("写作业")
tasks.append("跑步")
tasks.append("读书")
print(tasks)

tasks[1] = "看电影"
print(tasks)

del tasks[2]
print(tasks)
print(len(tasks))