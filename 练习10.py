'''题目'''
'''
用 for 循环计算 1 + 2 + 3 + ... + 100 的和，并打印结果。

提示：可以用 range(1, 101) 来生成 1 到 100 的整数序列（这个我们马上细讲，你先查一下或试着用）。

（如果感觉困难，也可以先写一个 while 版本的，然后尝试改成 for 版本。）
'''

'''回答'''
t = 0
for i in range(1,101):
    print(i)
    t += i
    print(t)


'''优化'''
t = 0
for i in range(1, 101):
    t += i
print(f"1 到 100 的总和是：{t}")   # 只打印最终结果



'''理论'''
'''
小知识：range() 是什么？
range(start, end) 会生成一个整数序列，包含 start，不包含 end。

range(1, 101) → 生成 1,2,3,…,100
常配合 for 循环：for i in range(5): → i 依次为 0,1,2,3,4（start 省略时默认从0开始）
'''