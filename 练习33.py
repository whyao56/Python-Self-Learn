'''
分组统计：groupby——数据分析的利器

现在你已经能筛选数据了，但如果我想知道**每个城市的平均气温**，或者**按月份统计销售额**，该怎么办？
这时候就要用到 `groupby`，它能把数据按照某个分类变量（如城市、月份）分组，然后对各组进行计算。

### 🌰 例子：按城市分组计算平均最高温
假设我们有多个城市的多条温度记录（比如每天一条）。
我们还是用现有的 `weather.csv`（每个城市只有一条），但为了演示分组，我们创建一个稍微复杂点的数据集：
```python
import pandas as pd

data = {
    "城市": ["北京", "北京", "北京", "上海", "上海", "上海", "广州", "广州"],
    "日期": ["周一","周二","周三","周一","周二","周三","周一","周二"],
    "最高温": [5, 7, 6, 15, 16, 17, 22, 24],
    "最低温": [-3, -1, -2, 8, 9, 10, 15, 17]
}
df = pd.DataFrame(data)
print(df)
```

现在，如果我想看每个城市的**平均最高温**，可以这样：
```python
grouped = df.groupby("城市")["最高温"].mean()
print(grouped)
```
输出：
```
城市
北京     6.000000
上海    16.000000
广州    23.000000
Name: 最高温, dtype: float64
```

**如果要多列统计**，用 `agg` 方法：
```python
stats = df.groupby("城市").agg({"最高温": "mean", "最低温": "min"})
print(stats)
```
这就会得到每个城市的平均最高温和最低温的最小值。

'''

