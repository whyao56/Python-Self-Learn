'''错误'''
'''
input() 返回的是字符串（如 "8"），而 a + b 计算得到的是整数 8。
Python 中 "8" 和 8 是不同类型，永远不相等，所以即使你输入 8，循环条件 guess != a + b 仍然为 True，程序会一直让你重新输入，无限循环。
'''

'''优化'''
a = 3
b = 5

answer = a + b
guess = int(input(f"{a} + {b} = "))    # 直接转成整数

while guess != answer:
    print("再想想！")
    guess = int(input(f"{a} + {b} = "))   # 每次重新输入后也要转成整数

print("正确！答对啦！")