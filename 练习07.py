'''理论'''
'''
让程序反复做——循环（while / for）
现在程序能输入、能判断，但都是一次性的。如果想让程序**重复做某事**（比如猜数字直到猜中、打印列表所有元素），就要用**循环**。

### 🌰 先看例子（while 循环）
```python
# 猜密码小游戏
secret = "python123"
guess = input("请输入密码：")

while guess != secret:                  # 只要猜错，就一直循环
    print("密码错误，请重试！")
    guess = input("请输入密码：")       # 再次询问

print("密码正确，欢迎进入系统！")        # 循环结束后才执行
```

### 📖 理论解释
- **while** 循环像一个**守门人**：当条件为 `True` 时，反复执行缩进的代码块；一旦条件变为 `False`，就跳出循环，执行后面的语句。
- 上面的例子中，只要 `guess != secret`（错误密码），就会不断让你重试，直到输对为止。
- **危险**：如果条件永远不变成 `False`，就会变成**死循环**（比如 `while True:`），程序永远卡在那里。通常需要内部有改变条件的语句（比如重新输入）。

### 🛠️ 逐行解释
1. 设定密码 `secret`。
2. 第一次输入密码。
3. `while guess != secret:` 判断输入是否**不等于**密码，如果不等于（条件为真），进入循环体。
4. 循环体里打印错误提示，并再次让用户输入（**这一行是跳出循环的关键**，否则密码永远不变，死循环）。
5. 一旦用户输入正确，`guess != secret` 为假，跳过循环，执行最后的欢迎信息。
'''



