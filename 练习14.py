'''回答'''
users = {
    "小明": "123456",
    "小红": "abc123",
    "小刚": "qwerty"
}
name = input("请输入用户名：")
if name in users:
    print(f"密码是：{users[name]}")
else:
    print("用户不存在")
    name = input("请输入用户名：")


