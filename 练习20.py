'''优化思路'''
'''
### 💡 常见原因（你可以任选两条回答）
1. **当前工作目录下没有叫 `data.txt` 的文件**。
   - 程序只会在你执行代码的那个文件夹里找，如果文件在别的位置，必须写出完整路径。
2. **文件名拼写错误**。
   - 比如实际文件是 `data.txt`，你写成了 `data.txt`（多了空格、大小写错误等）。Windows 不太区分大小写，但 macOS/Linux 会。
3. **文件扩展名被隐藏**。
   - 有些电脑隐藏了扩展名，你看文件叫 `data`，实际全名是 `data.txt`，但代码里写了 `data.txt` 可能找不到，或反过来。
4. **路径问题**。
   - 如果文件在子文件夹里，要写成 `"folder/data.txt"` 或 `"./folder/data.txt"`。
5. **文件被占用或权限不足**（较少见，但也会发生）。

### 🛠️ 解决方法：
- 用 `os.getcwd()` 查看当前目录，确认文件是否在里面。
- 用绝对路径，如 `open("C:/Users/xxx/Desktop/data.txt")`。
- 使用 `try...except` 捕获异常，友好提示用户（异常处理我们后面会讲）。
'''


